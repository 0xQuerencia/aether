#!/usr/bin/env python3
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any


HOME = Path.home()
HYPR_DIR = HOME / ".config/hypr"
LUA_CONFIG = HYPR_DIR / "hyprland.lua"
SETTINGS_LUA = HYPR_DIR / "hyprland/settings.lua"
SETTINGS_CONF = HYPR_DIR / "hyprland/settings.conf"
FOOT_INI = HOME / ".config/foot/foot.ini"
HEADER_LUA = "-- Generated by the Settings window.\n"
HEADER_CONF = "# Written by the Settings window (Super+I). Sourced last in hyprland.conf.\n"
OPTION_RE = re.compile(r"^[a-z_]+(:[a-z0-9_-]+)+$")
PART_RE = re.compile(r"^[a-z_][a-z0-9_]*$")
RATE_OPTIONS = (60, 120, 144, 165, 240)
ENTRY_RE = re.compile(r"^-- hyprset-entry: (.+)$")


def run_hyprctl(*args: str) -> subprocess.CompletedProcess[str] | None:
    try:
        return subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=3)
    except (OSError, subprocess.SubprocessError):
        return None


def hyprctl(*args: str) -> str:
    result = run_hyprctl(*args)
    return result.stdout if result and result.returncode == 0 else ""


def get_option(option: str) -> Any:
    try:
        data = json.loads(hyprctl("getoption", option, "-j"))
    except (ValueError, TypeError):
        return None
    if not isinstance(data, dict):
        return None
    for key in ("int", "float", "str", "bool"):
        if key in data:
            return data[key]

    def first_scalar(value: Any) -> Any:
        parts = str(value).split()
        if not parts:
            return None
        first = parts[0]
        try:
            return int(first)
        except ValueError:
            try:
                return float(first)
            except ValueError:
                return first

    if "css" in data:
        return first_scalar(data["css"])
    return first_scalar(data.get("custom", ""))


def merge_nested_config(target: dict[str, Any], source: dict[str, Any], option: str) -> None:
    for key, value in source.items():
        if key not in target:
            target[key] = value
        elif isinstance(target[key], dict) and isinstance(value, dict):
            merge_nested_config(target[key], value, option)
        else:
            raise ValueError(f"overlapping option keys: {option}")


def internal_monitor() -> dict[str, Any] | None:
    try:
        monitors = json.loads(hyprctl("monitors", "-j"))
    except (ValueError, TypeError):
        return None
    if not monitors:
        return None
    return next((monitor for monitor in monitors if monitor.get("name", "").startswith("eDP")), monitors[0])


def get_foot_alpha() -> float | None:
    try:
        match = re.search(r"^alpha=([0-9.]+)", FOOT_INI.read_text(), re.M)
        return float(match.group(1)) if match else 1.0
    except OSError:
        return None


def get(keys: list[str]) -> dict[str, Any]:
    values = {}
    for key in keys:
        if key == "rate":
            monitor = internal_monitor()
            values[key] = round(monitor["refreshRate"]) if monitor else None
        elif key == "footAlpha":
            values[key] = get_foot_alpha()
        elif OPTION_RE.fullmatch(key):
            value = get_option(key)
            if value is None and "-" in key:
                
                value = get_option(key.replace("-", "_"))
            values[key] = value
    return values


def fmt(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float):
        return f"{value:.3g}"
    return str(value)


def lua_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return fmt(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    raise ValueError("setting values must be strings, numbers, or booleans")


def nested_config(key: str, value: Any) -> dict[str, Any]:
    
    parts = key.replace("-", "_").split(":")
    if not parts or not all(PART_RE.fullmatch(part) for part in parts):
        raise ValueError(f"invalid Hyprland option key: {key}")
    tree = {}
    branch = tree
    for part in parts[:-1]:
        branch[part] = {}
        branch = branch[part]
    branch[parts[-1]] = value
    return tree


def render_lua_table(tree: dict[str, Any]) -> str:
    values = []
    for key in sorted(tree):
        value = tree[key]
        rendered = render_lua_table(value) if isinstance(value, dict) else lua_value(value)
        values.append(f"{key} = {rendered}")
    return "{ " + ", ".join(values) + " }"


def monitor_record(monitor: dict[str, Any], rate: int) -> dict[str, Any]:
    return {
        "output": monitor["name"],
        "mode": f"{monitor['width']}x{monitor['height']}@{rate}",
        "position": f"{monitor['x']}x{monitor['y']}",
        "scale": monitor["scale"],
    }


def render_entry(key: str, entry: dict[str, Any]) -> str:
    if key == "rate":
        monitor = entry["monitor"]
        return "hl.monitor({ output = %s, mode = %s, position = %s, scale = %s })" % (
            lua_value(monitor["output"]), lua_value(monitor["mode"]),
            lua_value(monitor["position"]), lua_value(monitor["scale"]),
        )
    return "hl.config(" + render_lua_table(nested_config(key, entry["value"])) + ")"


def read_lua_entries(path: Path | None = None) -> dict[str, dict[str, Any]]:
    path = path or SETTINGS_LUA
    entries = {}
    try:
        lines = path.read_text().splitlines()
    except OSError:
        return entries
    for line in lines:
        match = ENTRY_RE.match(line)
        if not match:
            continue
        try:
            entry = json.loads(match.group(1))
        except ValueError:
            continue
        if isinstance(entry, dict) and isinstance(entry.get("key"), str):
            entries[entry["key"]] = entry
    return entries


def render_settings_lua(entries: dict[str, dict[str, Any]]) -> str:
    lines = [HEADER_LUA.rstrip()]
    for key in sorted(entries):
        entry = entries[key]
        lines.append("-- hyprset-entry: " + json.dumps(entry, sort_keys=True, ensure_ascii=False, separators=(",", ":")))
        lines.append(render_entry(key, entry))
    return "\n".join(lines) + "\n"


def write_atomic(path: Path | str, content: str) -> bool:
    path = Path(path)
    encoded = content.encode("utf-8")
    try:
        if path.read_bytes() == encoded:
            return False
    except OSError:
        pass
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(encoded)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return True


def persist_lua(entries: dict[str, dict[str, Any]]) -> bool:
    return write_atomic(SETTINGS_LUA, render_settings_lua(entries))


def monitor_spec(monitor: dict[str, Any], rate: int) -> str:
    record = monitor_record(monitor, rate)
    return ", ".join((record["output"], record["mode"], record["position"], fmt(record["scale"])))


def read_conf_lines() -> list[str]:
    try:
        return SETTINGS_CONF.read_text().splitlines()
    except OSError:
        return []


def persist_conf(updates: dict[str, str]) -> bool:
    body = [line for line in read_conf_lines() if line.strip() and not line.lstrip().startswith("#")]
    for key, value in updates.items():
        if key.startswith("monitor="):
            output = key.split("=", 1)[1]
            body = [line for line in body if not (line.split("=", 1)[0].strip() == "monitor" and
                     line.split("=", 1)[1].strip().split(",", 1)[0] == output)]
        else:
            body = [line for line in body if line.split("=", 1)[0].strip() != key]
        body.append(value)
    content = HEADER_CONF + "\n".join(body) + "\n"
    return write_atomic(SETTINGS_CONF, content)


def set_foot_alpha(value: float) -> None:
    content = FOOT_INI.read_text()
    updated = re.sub(r"^alpha=[0-9.]+", f"alpha={value:.2f}", content, count=1, flags=re.M)
    write_atomic(FOOT_INI, updated)


def apply_lua(values: dict[str, Any], monitor_value: dict[str, Any] | None = None) -> bool:
    config = {}
    calls = []
    for key, value in values.items():
        merge_nested_config(config, nested_config(key, value), key)
    if config:
        calls.append("hl.config(" + render_lua_table(config) + ")")
    if monitor_value:
        m = monitor_value
        calls.append("hl.monitor({ output = %s, mode = %s, position = %s, scale = %s })" % (
            lua_value(m["output"]), lua_value(m["mode"]), lua_value(m["position"]), lua_value(m["scale"]),
        ))
    if not calls:
        return True
    result = run_hyprctl("eval", "; ".join(calls))
    return bool(result and result.returncode == 0 and "error" not in result.stdout.lower())


def apply_keywords(values: dict[str, Any], monitor_value: str | None = None) -> bool:
    commands = ["keyword %s %s" % (key, fmt(value)) for key, value in values.items()]
    if monitor_value:
        commands.append("keyword monitor " + monitor_value)
    if not commands:
        return True
    result = run_hyprctl("--batch", "; ".join(commands))
    return bool(result and result.returncode == 0)


def set_many(values: dict[str, Any]) -> bool:
    option_values = {}
    lines = {}
    entries = read_lua_entries()
    monitor_value = None
    monitor_metadata = None
    for key, value in values.items():
        if key == "rate":
            try:
                rate = int(value)
            except (TypeError, ValueError):
                continue
            monitor = internal_monitor()
            if not monitor or rate not in RATE_OPTIONS:
                continue
            record = monitor_record(monitor, rate)
            monitor_value = monitor_spec(monitor, rate)
            monitor_metadata = record
            lines["monitor=" + monitor["name"]] = "monitor = " + monitor_value
            entries[key] = {"key": key, "value": rate, "monitor": record}
        elif key == "footAlpha":
            set_foot_alpha(max(0.3, min(1.0, float(value))))
        elif OPTION_RE.fullmatch(key):
            if not isinstance(value, (str, int, float, bool)):
                continue
            option_values[key] = value
            formatted = fmt(value)
            lines[key] = f"{key} = {formatted}"
            entries[key] = {"key": key, "value": value}
    lua_mode = LUA_CONFIG.is_file()
    if lua_mode:
        applied = apply_lua(option_values, monitor_metadata)
        if not applied:
            applied = apply_keywords(option_values, monitor_value)
        persist_lua(entries)
    else:
        applied = apply_keywords(option_values, monitor_value)
        persist_conf(lines)
    return applied


def main(argv: list[str]) -> int:
    if len(argv) >= 2 and argv[1] == "get":
        sys.stdout.write(json.dumps(get(argv[2:])) + "\n")
        return 0
    if len(argv) == 3 and argv[1] == "set":
        values = json.loads(argv[2])
        if not isinstance(values, dict):
            raise ValueError("set expects a JSON object")
        return 0 if set_many(values) else 1
    sys.stderr.write("usage: hyprset.py get KEY... | set JSON\n")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
